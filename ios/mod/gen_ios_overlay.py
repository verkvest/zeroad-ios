#!/usr/bin/env python3
"""Generates gui/session/session_objects/ios_toolbar.xml (iOS port, GPL-2.0+).
Buttons are 72 GUI units = 48pt at the phone GUI scale (2.0 on a 3x display)."""
import os
B, STEP, COLS = 72, 76, 7
BUTTONS = [  # id, icon (or None = text button), caption, tooltip
    ("pause", None, "Pause", "Pause or resume the game"),
    ("speed", None, "Speed", "Change the game speed"),
    ("idleworker", "session/minimap-idle.png", "Idle", "Select the next idle worker"),
    ("workers", "session/icons/economics.png", "Workers", "Select all your workers and citizens"),
    ("army", "session/icons/attack-request.png", "Army", "Select your whole army"),
    ("home", "session/icons/focus-rally.png", "Home", "Select the Civic Centre (press again for the next one)"),
    ("camera", "session/icons/focus-flare.png", "Camera", "Reset the camera to the default angle and zoom"),
    ("stop", "session/icons/stop.png", "Stop", "Stop the selected units"),
    ("work", "session/icons/back-to-work.png", "Work", "Send the selected units back to work"),
    ("unload", "session/icons/garrison-out.png", "Unload", "Unload all garrisoned units"),
    ("delete", "session/icons/kill.png", "Delete", "Delete the selection"),
    ("info", "session/icons/encyclopaedia.png", "Info", "Show or hide the details of the selection (health, stats, portraits)"),
    ("map", None, "Map", "Show or hide the minimap"),
]
rows = (len(BUTTONS) + COLS - 1) // COLS
out = ['<?xml version="1.0" encoding="utf-8"?>',
       '<!-- iOS port (GPL-2.0+): phone overlay - toolbar for keyboard-only actions, deselect, grid paging,',
       '     long-press ring. Generated by ios/mod/gen_ios_overlay.py. -->',
       '<object name="iosOverlay" size="0 0 100% 100%" z="30">',
       '\t<action on="Tick">iosToolbarTick();</action>',
       '\t<object name="iosToolbar" size="2 54 %d %d">' % (2 + COLS * STEP - 4, 54 + rows * STEP - 4)]
for i, (bid, icon, caption, tip) in enumerate(BUTTONS):
    x, y = (i % COLS) * STEP, (i // COLS) * STEP
    out.append('\t\t<object name="iosButton_%s" type="button" style="StoneButton" size="%d %d %d %d" tooltip_style="sessionToolTip" tooltip="%s">' % (bid, x, y, x + B, y + B, tip))
    if icon:
        out.append('\t\t\t<object name="iosIcon_%s" type="image" ghost="true" size="14 3 58 47" sprite="stretched:%s"/>' % (bid, icon))
        out.append('\t\t\t<object name="iosLabel_%s" type="text" ghost="true" size="0 44 100%% 100%%" font="sans-bold-stroke-14" textcolor="white" text_align="center" text_valign="center">' % bid)
    else:
        out.append('\t\t\t<object name="iosLabel_%s" type="text" ghost="true" size="0 0 100%% 100%%" font="sans-bold-stroke-18" textcolor="white" text_align="center" text_valign="center">' % bid)
    out.append('\t\t\t\t<translatableAttribute id="caption">%s</translatableAttribute>' % caption)
    out.append('\t\t\t</object>')
    out.append('\t\t\t<action on="Press">iosToolbarPress("%s");</action>' % bid)
    out.append('\t\t</object>')
out.append('\t</object>')
out += [
    '\t<!-- Deselect: a 66 x 66 (44pt) X next to the selection details, positioned by ios_hud.js. -->',
    '\t<object name="iosDeselect" type="button" style="StoneButton" size="0 0 66 66" hidden="true" tooltip_style="sessionToolTip" tooltip="Deselect">',
    '\t\t<object type="text" ghost="true" size="0 0 100% 100%" font="sans-bold-stroke-24" textcolor="white" text_align="center" text_valign="center">X</object>',
    '\t\t<action on="Press">iosToolbarPress("deselect");</action>',
    '\t</object>',
    '\t<!-- Paging of the build / train grid (2 rows per page). -->',
    '\t<object name="iosPageButton" type="button" style="StoneButton" size="0 0 72 72" hidden="true" tooltip_style="sessionToolTip" tooltip="Next page of buttons">',
    '\t\t<object name="iosPageLabel" type="text" ghost="true" size="0 0 100% 100%" font="sans-bold-stroke-18" textcolor="white" text_align="center" text_valign="center"/>',
    '\t\t<action on="Press">iosToolbarPress("page");</action>',
    '\t</object>',
    '\t<!-- Long press armed (box select): a ring under the finger for half a second. -->',
    '\t<object name="iosArmedRing" type="image" ghost="true" hidden="true" size="0 0 96 96" sprite="stretched:session/minimap_circle_modern.png"/>',
    '</object>', '']
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "gui", "session", "session_objects", "ios_toolbar.xml")
open(path, "w", encoding="utf-8").write("\n".join(out))
print("wrote", path)
